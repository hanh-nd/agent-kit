#!/usr/bin/env node
/**
 * Derives provider-native permission rules from the same policy constants the
 * hook enforces, so runtime-native enforcement stays in sync with the
 * portable hook. Output: native-permissions.json at the plugin root.
 *
 * The hook remains the portable enforcement layer; these rules are the
 * recommended merge into the user's project settings for providers whose
 * runtime enforces permissions deterministically (phrase-independent).
 */
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'node:url';
import { FORBIDDEN_DIRS, FORBIDDEN_FILES } from './security/constants.js';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.resolve(__dirname, '..', '..', 'native-permissions.json');
/** Glob extensions not derivable from FORBIDDEN_FILES mechanically. */
const EXTRA_GLOBS = ['**/.env.*', '**/*.pem', '**/id_rsa*', '**/id_ed25519*'];
export function deriveClaudeDenyRules() {
    const rules = [];
    for (const file of FORBIDDEN_FILES) {
        rules.push(`Read(${file})`, `Edit(${file})`, `Write(${file})`);
    }
    for (const dir of FORBIDDEN_DIRS) {
        rules.push(`Read(${dir}/**)`, `Edit(${dir}/**)`, `Write(${dir}/**)`);
    }
    for (const glob of EXTRA_GLOBS) {
        rules.push(`Read(${glob})`, `Edit(${glob})`, `Write(${glob})`);
    }
    return rules;
}
export function buildNativePermissions() {
    return {
        _comment: 'Generated by scripts/generate-native-policy.ts from security/constants.ts. Merge the claude block into your project .claude/settings.json for runtime-native enforcement.',
        claude: { permissions: { deny: deriveClaudeDenyRules() } },
    };
}
export function main() {
    fs.writeFileSync(OUTPUT, `${JSON.stringify(buildNativePermissions(), null, 2)}\n`);
    console.log(`Wrote ${OUTPUT}`);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
    main();
}
